from django.conf import settings
from django.core.mail import EmailMultiAlternatives
from django.utils.html import escape


def _get_user_display_name(user):
    """
    Returns the most appropriate display name for the user.
    """

    full_name = (
        getattr(user, "get_full_name", lambda: "")()
        or ""
    ).strip()

    if full_name:
        return full_name

    username = (
        getattr(user, "username", "")
        or ""
    ).strip()

    if username:
        return username

    email = (
        getattr(user, "email", "")
        or ""
    ).strip()

    if email:
        return email.split("@")[0]

    return "there"


def _get_user_email(user):
    """
    Returns the user's registered email address.
    """

    return (
        getattr(user, "email", "")
        or ""
    ).strip()


def _get_notification_preferences(user):
    """
    Retrieves the user's email preferences.

    If preferences do not exist, they are created
    using the model's default values.
    """

    from .models import NotificationPreference

    preferences, _ = (
        NotificationPreference.objects.get_or_create(
            user=user
        )
    )

    return preferences


