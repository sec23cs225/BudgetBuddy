def send_notification_email(notification):
    """
    Sends a BudgetBuddy notification email.

    Returns:
        True  -> email sent
        False -> email skipped
    """

    user = notification.user

    recipient = _get_user_email(user)

    if not recipient:
        return False

    preferences = _get_notification_preferences(user)

    if not preferences.email_enabled:
        return False

    text_content, html_content = (
        _build_email_content(notification)
    )

    subject = (
        f"BudgetBuddy | "
        f"{notification.title}"
    )

    email = EmailMultiAlternatives(
        subject=subject,
        body=text_content,
        from_email=settings.DEFAULT_FROM_EMAIL,
        to=[recipient],
    )

    email.attach_alternative(
        html_content,
        "text/html",
    )

    email.send(
        fail_silently=False,
    )

    return True


